# ---------------------------------------------------------- V2-11..16 (LLM test)
tf = V2_RAW / f"llm_test_{mk}.csv"
if tf.exists():
    te = pd.read_csv(tf)
    h = te[te.kind == "harmful"]
    fam_order = [f for f in ORDER if f in set(te.family)]
    for regime in sorted(h.regime.unique()):
        hr = h[h.regime == regime]
        fig, ax = plt.subplots(2, 2, figsize=(11, 6.4))
        t = hr.pivot_table(index="family", columns="attack", values="asr", aggfunc="mean")
        t = t.reindex([f for f in fam_order if f in t.index])
        t.plot(kind="bar", ax=ax[0, 0], width=.8)
        ax[0, 0].set_ylabel("attack success rate"); ax[0, 0].set_xlabel("")
        ax[0, 0].legend(fontsize=6); ax[0, 0].tick_params(axis="x", rotation=35)
        ax[0, 0].set_title(f"FIG V2-11  ASR by held-out attack family [{regime}]")
        for f in fam_order:
            s = hr[hr.family == f].groupby("eps_pct").asr.mean()
            ax[0, 1].plot(s.index, s.values, "o-", ms=3, label=f, color=COL[f])
        ax[0, 1].set_xlabel(r"latent attack $\epsilon$ (% of activation norm)")
        ax[0, 1].set_ylabel("ASR"); ax[0, 1].legend(fontsize=6, ncol=2)
        ax[0, 1].set_title("FIG V2-12  latent-attack robustness curve")
        w = hr.groupby("family").asr.max().reindex(fam_order)
        ax[1, 0].barh(range(len(w)), w.values,
                      color=[COL[f] for f in w.index])
        ax[1, 0].set_yticks(range(len(w))); ax[1, 0].set_yticklabels(w.index)
        ax[1, 0].set_xlabel("WORST-CASE ASR over attack magnitude (lower better)")
        ax[1, 0].set_title("FIG V2-13  worst-scale robustness")
        sfe = te[(te.kind == "safe") & (te.regime == regime)]
        fr = sfe.groupby("family").refusal.mean()
        asr = hr.groupby("family").asr.mean()
        common = [f for f in fam_order if f in fr.index and f in asr.index]
        cx = fr.reindex(common).values; cy = 1 - asr.reindex(common).values
        ax[1, 1].scatter(cx, cy, c=[COL[f] for f in common], s=60, zorder=3)
        for f, x_, y_ in zip(common, cx, cy):
            ax[1, 1].annotate(f.replace("_", " "), (x_, y_), fontsize=6,
                              xytext=(3, 3), textcoords="offset points")
        pf = pareto_front(cx, cy)
        if len(pf) > 1:
            o = np.argsort(cx[pf]); ax[1, 1].plot(cx[pf][o], cy[pf][o], "k--", lw=1,
                                                   label="Pareto front")
            ax[1, 1].legend()
        ax[1, 1].set_xlabel("benign false-refusal rate (XSTest safe)  →  cost")
        ax[1, 1].set_ylabel("1 − ASR  →  safety")
        ax[1, 1].set_title("FIG V2-14  safety–utility Pareto frontier")
        save(fig, f"figV2_11_14_llm_{regime}.png")
        cap(f"FIG V2-11/12/13/14 [{regime}] — `figV2_11_14_llm_{regime}.png`",
            "Held-out attack templates and a continuous latent-attack sweep on "
            "the frozen test split. Regime A uses oracle harm labels (isolates "
            "the mechanism; benign cost is zero by construction), regime B uses "
            "the frozen learned detector (the only regime in which the Pareto "
            "panel is meaningful).")

    # V2-15 / V2-16
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.6))
    e = h.groupby("family")[["int_mean", "int_energy"]].mean().reindex(fam_order)
    ax[0].bar(range(len(e)), e.int_mean.values, color=[COL[f] for f in e.index])
    ax[0].set_xticks(range(len(e))); ax[0].set_xticklabels(e.index, rotation=35, ha="right")
    ax[0].set_ylabel(r"realised mean $\|\Delta h\|$")
    ax[0].set_title("FIG V2-15  realised intervention (analytic budget matched)")
    KEY = ["regime", "attack", "eps_pct", "pid"]
    pv = h.groupby(KEY + ["family"]).asr.mean().unstack("family")
    rows = []
    for c in [f for f in fam_order if f not in ("L7_cantor",)]:
        sub = pv[["L7_cantor", c]].dropna()
        if len(sub) < 10: continue
        st = paired_bootstrap(-sub["L7_cantor"].values, -sub[c].values, seed=9)
        rows.append((c, st["mean_diff"], st["ci_lo"], st["ci_hi"], st["n"]))
    if rows:
        nm = [r[0] for r in rows]; md = [r[1] for r in rows]
        lo = [r[1] - r[2] for r in rows]; hi = [r[3] - r[1] for r in rows]
        y = np.arange(len(nm))
        ax[1].errorbar(md, y, xerr=[lo, hi], fmt="o", color="#1f77b4", capsize=3)
        ax[1].axvline(0, color="k", lw=1)
        ax[1].set_yticks(y); ax[1].set_yticklabels(nm)
        ax[1].set_xlabel(r"$\Delta(-\mathrm{ASR})$: Cantor $-$ control (>0 = Cantor safer)")
        ax[1].set_title("FIG V2-16  paired difference on the frozen test")
    save(fig, "figV2_15_16_budget_paired.png")
    cap("FIG V2-15/16 — `figV2_15_16_budget_paired.png`",
        "Left: realised intervention norm. The analytic budget "
        r"$\int c\,dr = B_{total}$ is identical by construction; what differs is "
        "how much of it a trajectory actually spends. Right: the pre-registered "
        "primary comparison, paired on (regime, attack, eps, prompt).")

