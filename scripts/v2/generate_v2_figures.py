# ---------------------------------------------------------------- V2-01..04
n = 6; E0 = 1.0 / n
L = build_layout("L7_cantor", n, E0)
r = np.linspace(0, 1, 200001)

fig, ax = plt.subplots(2, 1, figsize=(9, 4.6), sharex=True)
for g in L.gaps:
    ax[0].add_patch(plt.Rectangle((g.a, g.level - .4), g.width, .8,
                                  color=plt.cm.viridis((g.level - 1) / (n - 1))))
ax[0].set_ylim(n + .6, .4); ax[0].set_ylabel("removal level $k$")
ax[0].set_yticks(range(1, n + 1))
ax[0].set_title(f"FIG V2-01  Cantor gaps to level n={n}: "
                r"$N_k=2^{k-1}$ gaps of width $w_k=3^{-k}$")
ax[0].axvline(.5, color="k", ls="--", lw=1)
ax[0].text(.5, .2, " decision boundary r=1/2", fontsize=7, va="top")
ax[1].plot(r, L.field(r), lw=.7, color="#1f77b4")
ax[1].set_xlabel("threat coordinate $r$"); ax[1].set_ylabel(r"$V'(r)$")
ax[1].set_title(r"scale-compensated field: peak of level $k$ is $3E_0(3/2)^k$")
save(fig, "figV2_01_gap_levels.png")
cap("FIG V2-01 — `figV2_01_gap_levels.png`",
    f"Cantor gap structure to level n={n} (colour = removal level) and the "
    r"resulting control field $V'(r)$. $r=1/2$ is the refusal decision "
    "boundary; the level-1 gap straddles it by construction.")

fig, ax = plt.subplots(1, 3, figsize=(11, 3.1))
for k in range(1, n + 1):
    gs = [g for g in L.gaps if g.level == k]
    xx = np.linspace(0, 1, 4001)
    Lk = build_layout("L7_cantor", n, E0)
    ax[0].plot(xx, [max([Lk.coef[i] * 6 * ((x - Lk.las[i]) / Lk.wid[i]) *
                         (1 - (x - Lk.las[i]) / Lk.wid[i])
                         if Lk.las[i] < x < Lk.lbs[i] else 0
                         for i in range(len(Lk.gaps)) if Lk.gaps[i].level == k] + [0])
                    for x in xx], lw=.8, label=f"k={k}",
               color=plt.cm.viridis((k - 1) / (n - 1)))
ax[0].set_xlabel("$r$"); ax[0].set_ylabel(r"$|V'_k(r)|$"); ax[0].legend(ncol=2)
ax[0].set_title("FIG V2-02  field by level")
ks = np.arange(1, n + 1)
ax[1].bar(ks, [E0] * n, color="#1f77b4")
ax[1].axhline(E0, color="r", ls="--", label=f"$E_0$ = {E0:.4f}")
ax[1].set_xlabel("level $k$"); ax[1].set_ylabel(r"$\sum_j\int|V'_{k,j}|$")
ax[1].set_ylim(0, E0 * 1.6); ax[1].legend()
ax[1].set_title("FIG V2-03  Theorem A: level action is constant")
pk = [L.peak_of_level(k) for k in ks]
ax[2].semilogy(ks, pk, "o-", color="#d62728")
sl = np.polyfit(ks, np.log(pk), 1)[0]
ax[2].set_xlabel("level $k$"); ax[2].set_ylabel(r"$\|V'_k\|_\infty$")
ax[2].set_title(f"FIG V2-04  Theorem B: slope={sl:.6f}, log(3/2)={np.log(1.5):.6f}")
save(fig, "figV2_02_04_theorems.png")
cap("FIG V2-02/03/04 — `figV2_02_04_theorems.png`",
    "Left: the field contributed by each removal level. Middle: Theorem A — "
    r"every level carries the same total action $E_0=B_{total}/n$. Right: "
    r"Theorem B — the peak magnitude grows exactly as $(3/2)^k$, restoring the "
    "scale law V1 normalised away. Both hold identically for every "
    "width-matched control, so neither supports a Cantor-specific claim.")

# ---------------------------------------------------------------- V2-05, 06
if have("synthetic_main.csv"):
    sy = pd.read_csv(V2_RAW / "synthetic_main.csv")
    sy["safe"] = 1 - sy.crossed.astype(float)
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.6))
    for c in [c for c in sy.ctrl.unique()]:
        s = sy[sy.ctrl == c].groupby("A")["safe"].mean()
        ax[0].semilogx(s.index, s.values, "o-", ms=3, lw=1.4,
                       label=c, color=BCOL.get(c, "k"))
    ax[0].set_xlabel("attack amplitude $A$ (log)"); ax[0].set_ylabel("P(safe)")
    ax[0].legend(ncol=2, fontsize=6)
    ax[0].set_title("FIG V2-05  synthetic robustness vs log amplitude\n"
                    "(55 680 sims, 3 fields, 5 attack families)")
    KEY = ["n", "field", "A", "attack", "phase", "r0"]
    piv = sy.groupby(KEY + ["ctrl"])["safe"].mean().unstack("ctrl").dropna()
    names, mids, los, his = [], [], [], []
    for c in ["B0_none", "B1_constant", "B2_central", "B3_periodic",
              "B4_random", "B5_shuffled", "B6_center_anchored"]:
        if c not in piv: continue
        st = paired_bootstrap(piv["B7_cantor"].values, piv[c].values, seed=5)
        names.append(c.replace("B", "").replace("_", " ")); mids.append(st["mean_diff"])
        los.append(st["mean_diff"] - st["ci_lo"]); his.append(st["ci_hi"] - st["mean_diff"])
    y = np.arange(len(names))
    ax[1].errorbar(mids, y, xerr=[los, his], fmt="o", color="#1f77b4", capsize=3)
    ax[1].axvline(0, color="k", lw=1)
    ax[1].set_yticks(y); ax[1].set_yticklabels(names)
    ax[1].set_xlabel(r"$\Delta$ P(safe): Cantor $-$ control  (>0 = Cantor better)")
    ax[1].set_title("FIG V2-06  paired difference, 95% bootstrap CI")
    save(fig, "figV2_05_06_synthetic.png")
    cap("FIG V2-05/06 — `figV2_05_06_synthetic.png`",
        "Left: P(safe) against attack amplitude on a log axis; every controller "
        "collapses at large A, and the discrimination happens at A in [2,6]. "
        "Right: paired bootstrap of Cantor minus each control over 1920 matched "
        "conditions. Cantor beats none/constant/periodic but LOSES to central "
        "and to shuffled, and is indistinguishable from center-anchored "
        "(d_z=0.049) — H3 and H4 rejected in the synthetic setting.")

